    private static void deactivateNow() {
        Log.i(TAG, "onDeactivate");
        active = false;
        ++activationGeneration;
        carplayRunning = false;
        carplayPresent = false;
        ClusterStateController.setCarPlaySessionActive(false);
        ClusterStateController.setRgiPresentationActive(false);
        StockPhoneKeyFilter.uninstall();   /* restore the stock phone controller */

        try {
            /* Stop modules */
            RouteGuidance old = routeGuidance;
            routeGuidance = null;
            try { if (old != null) old.stop(); }
            catch (Throwable t) { Log.e(TAG, "RGI teardown error", t); }
            releaseNaviService();

            /* Unregister listener */
            if (savedContext != null && listenerProxy != null) {
                IDeviceManager dm = getDeviceManager(savedContext);
                if (dm != null) {
                    unregisterListener(dm);
                }
            }

        } catch (Throwable t) {
            Log.e(TAG, "onDeactivate error", t);
        } finally {
            frameworkAccess = null; // KOMO teardown needs it until stop() finishes.
            releaseNaviService();
            registered = false;
            listenerProxy = null;
            savedContext = null;
            retrying = false;
            if (retryThread != null) retryThread.interrupt();
            retryThread = null;
            /* Drain any in-flight 2-finger gesture so iOS sees a
             * proper touch-up (not a cancel) — otherwise the next
             * session starts with a stuck-finger state.  Wrapped in
             * try/catch: shutdown must not prevent bus teardown. */
            try {
                CursorController.getInstance().shutdown();
            } catch (Throwable t) {
                Log.e(TAG, "input shutdown error", t);
            }
            /* Block up to 200 ms for the writer to actually put the
             * shutdown frames on the wire.  CarplayBus.stop() wipes
             * sendQueue[] inside closeConnectionLocked, so without
             * this flush the final touch-up + CMD_CURSOR_HIDE would
             * race the close and often lose. */
            try {
                CarplayBus.getInstance().flush(200);
            } catch (Throwable t) {
                Log.e(TAG, "bus flush error", t);
            }
            /* Tear down bus last — after every module has had a chance
             * to unsubscribe above.  stop() is idempotent. */
            CarplayBus.getInstance().stop();
        }
    }

