    private static boolean tryInit(Object context) {
        synchronized (RGI_LOCK) { return initNow(context); }
    }

    private static boolean initNow(Object context) {
        if (!active || savedContext != context) return false;
        Object naviService = isRgiWithdrawn() ? null : getNaviService(context);
        IDeviceManager deviceManager = getDeviceManager(context);
        /* NO RGI install keeps the lower-bar route text (road + ETA) only. It never
         * holds activation back: the resident monitor retries the service. */
        boolean textOnly = isRgiPresentationDisabled();

        if (deviceManager == null || (!isRgiWithdrawn() && !textOnly && naviService == null)) {
            return false;
        }

        /* Initialize route guidance module.
         * AmapRouteGuidance wraps the current implementation and only adds the
         * v38/iOS27 soft-inactive lifecycle compatibility; all current BAP,
         * renderer and stock-navigation handoff fixes remain in RouteGuidance
         * and BAPBridge. */
        if (!registerListener(deviceManager)) return false;
        if (routeGuidance != null) return true;
        if (isRgiWithdrawn() || naviService == null) return true;
        routeGuidance = new RouteGuidance(textOnly);
        if (!routeGuidance.init(naviService)) {
            long now = com.luka.carplay.framework.ElapsedClock.nowMs();
            if (lastInitFailureLog == 0 || now < lastInitFailureLog || now - lastInitFailureLog >= 10000L) {
                lastInitFailureLog = now;
                Log.e(TAG, "RouteGuidance init failed; retry pending");
            }
            try { routeGuidance.stop(); }
            catch (Throwable t) { Log.e(TAG, "failed RGI init cleanup", t); }
            routeGuidance = null;
            return textOnly;
        }

        /* Cover art is handled by TerminalModeBapCombi$EventListener */

        return true;
    }

    private static void startRetryThread(final Object context) {
        if (retrying) return;
        retrying = true;
        final int generation = activationGeneration;

        Thread t = new Thread(new Runnable() {
            public void run() {
                try {
                    int attempts = 0;
                    while (active && generation == activationGeneration) {
                        sleep(2000);
                        if (!active || generation != activationGeneration) break;

                        attempts++;
                        if (attempts % 10 == 1) {
                            Log.d(TAG, "Retry attempt " + attempts);
                        }

                        try {
                            if (active && generation == activationGeneration && tryInit(context)) {
                                Log.i(TAG, "Retry succeeded after " + attempts + " attempts");
                                return;
                            }
                        } catch (Throwable e) {
                            Log.d(TAG, "Retry error: " + e.getMessage());
                        }
                    }
                } finally {
                    synchronized (RGI_LOCK) {
                        if (retryThread == Thread.currentThread()) {
                            retrying = false;
                            retryThread = null;
                        }
                    }
                }
            }
        }, "CarPlayHook-Retry");
        t.setDaemon(true);
        retryThread = t;
        t.start();
    }

