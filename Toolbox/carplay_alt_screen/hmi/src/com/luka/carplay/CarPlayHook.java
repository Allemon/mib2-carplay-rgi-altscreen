    private static void activateNow(Object context) {
        if (active && savedContext != context) deactivateNow();
        ++activationGeneration;
        Log.refreshLevel();
        Log.i(TAG, "onActivate");
        Log.i(TAG, "Build: " + BUILD_ID);

        /* Construct CursorController (touchpad-input controller; the
         * name is legacy from when this drove an on-screen cursor).
         * Trivial singleton init — no bus traffic — but we touch it
         * here so the DSI patch's setTouchSink() lands on a live
         * instance from the first event. */
        CursorController.getInstance();

        /* Kick the bus up front so every module has a live channel
         * to the hook before the first CarPlay event fires.  Both install
         * modes: the OEM map gate (0x0119) needs it even without RGI.
         * Idempotent. */
        CarplayBus.getInstance().start();

        /* Cluster telephone tab: CarPlay call state and dialing from the stock
         * terminal-mode event bus.  Once per bus, every install mode; it never
         * throws into the activation. */
        TelephonyEventBridge.attach(context);
        StockPhoneKeyFilter.install(context);   /* drop the duplicate stock MFL phone key during a gated CarPlay call; no-op if unreachable */

        active = true;
        carplayPresent = true;
        savedContext = context;
        frameworkAccess = extractFramework(context);
        ClusterStateController.start(frameworkAccess);
        ClusterStateController.setCarPlaySessionActive(true);
        startRgiRuntimeMonitor();

        try {
            if (tryInit(context)) {
                Log.i(TAG, "Initialized on first attempt");
                return;
            }

            Log.i(TAG, "Starting retry thread");
            startRetryThread(context);

        } catch (Throwable t) {
            Log.e(TAG, "onActivate error", t);
            startRetryThread(context);
        }
    }

